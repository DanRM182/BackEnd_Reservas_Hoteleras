CREATE TABLE HABITACION(
ID_HABITACION NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
NUMERO_HABITACION VARCHAR2 (20) NOT NULL,
TIPO_HABITACION VARCHAR2 (20) NOT NULL,
ESTADO_HABITACION VARCHAR2 (30) NOT NULL,
ESTADO_REGISTRO VARCHAR2 (10) NOT NULL,
PRECIO NUMBER (10,2) NOT NULL,
CAPACIDAD NUMBER NOT NULL,

 CONSTRAINT PK_ID_HABITACION
      PRIMARY KEY (ID_HABITACION),

  CONSTRAINT CHK_HABITACION_CAPACIDAD
      CHECK (CAPACIDAD IS NOT NULL AND CAPACIDAD > 0),

  CONSTRAINT CHK_HABITACION_PRECIO
      CHECK (PRECIO IS NOT NULL AND PRECIO > 0),

  CONSTRAINT CHK_HABITACION_REGISTRO
      CHECK (TRIM(ESTADO_REGISTRO) IS NOT NULL AND TRIM(ESTADO_REGISTRO) IN ('ACTIVO', 'ELIMINADO')),

  CONSTRAINT CHK_HABITACION_ESTADO
      CHECK (
          TRIM(ESTADO_HABITACION) IS NOT NULL
          AND TRIM(ESTADO_HABITACION) IN (
              'DISPONIBLE',
              'OCUPADA',
              'LIMPIEZA',
              'MANTENIMIENTO')),


CONSTRAINT CHK_HABITACION_TIPO
    CHECK (
        TRIM(TIPO_HABITACION) IS NOT NULL
            AND TRIM(TIPO_HABITACION) IN (
                                          'INDIVIDUAL',
                                          'DOBLE',
                                          'SUITE'
            )
        )



);

COMMIT;
