CREATE TABLE HUESPEDES (
    ID_HUESPED NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(50) NOT NULL,
    APELLIDO_PATERNO VARCHAR2(50) NOT NULL,
    APELLIDO_MATERNO VARCHAR2(50) NOT NULL,
    EMAIL VARCHAR2(100) NOT NULL,
    TELEFONO VARCHAR2(10) NOT NULL,
    DOCUMENTO VARCHAR(25) NOT NULL,
    NACIONALIDAD VARCHAR(25) NOT NULL,
    ESTADO_REGISTRO VARCHAR(10) NOT NULL,

    CONSTRAINT PK_HUESPED PRIMARY KEY (ID_HUESPED),
    
    CONSTRAINT CHK_HUESPED_NOMBRE
        CHECK (TRIM(NOMBRE) IS NOT NULL),

    CONSTRAINT CHK_HUESPED_APELLIDO_PATERNO
        CHECK (TRIM(APELLIDO_PATERNO) IS NOT NULL),

    CONSTRAINT CHK_HUESPED_APELLIDO_MATERNO
        CHECK (TRIM(APELLIDO_MATERNO) IS NOT NULL),

    CONSTRAINT CHK_HUESPED_EMAIL
        CHECK (TRIM(EMAIL) IS NOT NULL),

    CONSTRAINT CHK_HUESPED_TELEFONO
	    CHECK (REGEXP_LIKE(TELEFONO, '^[0-9]{10}$')),

    CONSTRAINT CHK_HUESPED_DOCUMENTO
        CHECK (TRIM(DOCUMENTO) IS NOT NULL),

    CONSTRAINT CHK_HUESPED_NACIONALIDAD
        CHECK (TRIM(NACIONALIDAD) IS NOT NULL),

    CONSTRAINT CHK_HUESPED_ESTADO_REGISTRO
        CHECK (ESTADO_REGISTRO IN('ACTIVO', 'ELIMINADO'))
);

COMMIT;