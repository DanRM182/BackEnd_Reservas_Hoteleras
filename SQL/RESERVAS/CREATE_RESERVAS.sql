CREATE TABLE RESERVAS (
    ID_RESERVA NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    ID_HABITACION NUMBER(10) NOT NULL,
    ID_HUESPED NUMBER(10) NOT NULL,
    ESTADO_RESERVA VARCHAR(15) NOT NULL,
    FECHA_ENTRADA DATE NOT NULL,
    FECHA_SALIDA DATE NOT NULL,

    CONSTRAINT PK_RESERVA PRIMARY KEY (ID_RESERVA),

    CONSTRAINT CHK_RESERVAS_ID_HABITACION
        CHECK (ID_HABITACION > 0),
    
    CONSTRAINT CHK_RESERVAS_ID_HUESPED
        CHECK (ID_HUESPED > 0),

    CONSTRAINT CHK_RESERVAS_ESTADO
        CHECK(ESTADO_RESERVA IN ('CONFIRMADA', 'EN_CURSO', 'FINALIZADA', 'CANCELADA')),

    CONSTRAINT CHK_RESERVAS_FECHAS 
        CHECK (FECHA_SALIDA > FECHA_ENTRADA)
);

COMMIT;